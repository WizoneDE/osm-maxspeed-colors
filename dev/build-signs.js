// Writes the official sign artwork from dev/signs/*.svg into generated/signs.js.
//
//   node dev/build-signs.js
//
// The SVG files are traffic signs from Wikimedia Commons, already optimised
// with svgo (ids prefixed per sign, numbers rounded to one decimal). Only the
// viewBox and the inner markup are kept; content.js puts them into <symbol>s.
const fs = require('fs');
const path = require('path');

const target = path.join(__dirname, '..', 'generated', 'signs.js');
const folder = path.join(__dirname, 'signs');

const entries = fs.readdirSync(folder).filter((f) => f.endsWith('.svg')).sort().map((file) => {
  const svg = fs.readFileSync(path.join(folder, file), 'utf8');
  const box = svg.match(/<svg[^>]*\bviewBox="0 0 ([\d.]+) ([\d.]+)"[^>]*>/);
  if (!box) throw new Error(`${file}: no viewBox "0 0 w h"`);
  const inner = svg.slice(svg.indexOf(box[0]) + box[0].length, svg.lastIndexOf('</svg>'));
  if (/<script|\son\w+=|javascript:|<image|<foreignObject/i.test(inner)) throw new Error(`${file}: unexpected content`);
  const key = file.slice(0, -'.svg'.length);
  return `  ${JSON.stringify(key)}: { width: ${box[1]}, height: ${box[2]}, svg: ${JSON.stringify(inner)} },\n`;
});

const output = [
  '// Generated by dev/build-signs.js from dev/signs/*.svg – do not edit by hand.\n',
  '//\n',
  '// Traffic signs from Wikimedia Commons (public domain as official works, in\n',
  '// Germany § 5 UrhG), optimised with svgo. Keys are the German sign numbers, other\n',
  '// countries\' signs start with the country code ("CH-2.59.1"); "snow" is the symbol\n',
  '// "Schnee- oder Eisglätte". Loaded just before content.js, which takes them from\n',
  '// this global (see "Generated data" there).\n',
  '(globalThis.__osmMaxspeedColorsData ??= {}).signArt = {\n',
  ...entries,
  '};\n',
].join('');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, output);
console.log(`${entries.length} signs, ${output.length} characters written to generated/signs.js`);
